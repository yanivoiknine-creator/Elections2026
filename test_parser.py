def run():
    failures = 0
    for name, text, expected, total in CASES:
        got = parse_seats(text)
        problems = []
        for k, v in expected.items():
            if got.get(k) != v:
                problems.append(f"{P.display(k)}: ציפינו {v}, קיבלנו {got.get(k)}")
        for k in set(got) - set(expected):
            problems.append(f"מיותר {P.display(k)}={got[k]:g}")
        s = sum(got.values())
        if s != total:
            problems.append(f"סכום {s:g} במקום {total}")

        if problems:
            failures += 1
            print(f"FAIL  {name}")
            for p in problems:
                print(f"        {p}")
        else:
            print(f"ok    {name}  ({len([1 for v in got.values() if v])} מפלגות, סכום {s:g})")

    print()
    print(f"{len(CASES) - failures}/{len(CASES)} עברו")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(run())
